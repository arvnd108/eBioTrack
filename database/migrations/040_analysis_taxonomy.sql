-- Owner: A (Backend)
-- Purpose: Tables, keys, CHECK/UNIQUE constraints: Analysis, Taxonomy & Analytics
--
-- Slice: Analysis, Taxonomy & Analytics (CONTRACT section 4.4)
-- Tables: dna_markers, analysis_runs, taxa, taxon_assignments, data_exports
--
-- Rules the schema alone enforces:
--   1. An approved analysis run must have approved_by and approved_at.
--   2. A taxon is unique per rank (scientific_name, rank).
--   3. One detection per analysis + library + taxon.
--
-- Columns marked "FK ... added in 090" reference other slices' tables and are plain bigint here,
-- so this file applies on its own after 001. FKs inside this slice use ON DELETE RESTRICT:
-- scientific records are never hard-deleted (D19). Primary keys start at 1000 so seed rows can
-- use explicit IDs below 1000 (D6).

CREATE TABLE dna_markers (
    marker_id     bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    marker_name   text NOT NULL,
    target_region text,
    CONSTRAINT pk_dna_markers PRIMARY KEY (marker_id),
    CONSTRAINT uq_dna_markers_marker_name UNIQUE (marker_name),
    CONSTRAINT ck_dna_markers_marker_name_not_blank CHECK (length(btrim(marker_name)) > 0)
);

CREATE TABLE analysis_runs (
    analysis_id          bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    -- FK to sequencing_runs added in 090
    run_id               bigint NOT NULL,
    marker_id            bigint NOT NULL,
    pipeline_name        text NOT NULL,
    pipeline_version     text NOT NULL,
    reference_db         text NOT NULL,
    reference_db_version text,
    parameters           jsonb DEFAULT '{}',
    status               analysis_status NOT NULL DEFAULT 'draft',
    -- FK to users added in 090
    imported_by          bigint,
    -- FK to users added in 090
    approved_by          bigint,
    approved_at          timestamptz,
    created_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_analysis_runs PRIMARY KEY (analysis_id),
    CONSTRAINT fk_analysis_runs_marker_id FOREIGN KEY (marker_id)
        REFERENCES dna_markers (marker_id) ON DELETE RESTRICT,
    CONSTRAINT ck_analysis_runs_approved_fields CHECK (
        status <> 'approved' OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)
    ),
    CONSTRAINT ck_analysis_runs_pipeline_name_not_blank CHECK (length(btrim(pipeline_name)) > 0),
    CONSTRAINT ck_analysis_runs_pipeline_version_not_blank CHECK (length(btrim(pipeline_version)) > 0),
    CONSTRAINT ck_analysis_runs_reference_db_not_blank CHECK (length(btrim(reference_db)) > 0)
);

CREATE TABLE taxa (
    taxon_id        bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    scientific_name text NOT NULL,
    rank            taxon_rank NOT NULL,
    parent_taxon_id bigint,
    external_id     text,
    CONSTRAINT pk_taxa PRIMARY KEY (taxon_id),
    -- Self-reference builds the hierarchy; RESTRICT keeps a parent while children exist.
    CONSTRAINT fk_taxa_parent_taxon_id FOREIGN KEY (parent_taxon_id)
        REFERENCES taxa (taxon_id) ON DELETE RESTRICT,
    CONSTRAINT uq_taxa_scientific_name_rank UNIQUE (scientific_name, rank),
    CONSTRAINT ck_taxa_not_own_parent CHECK (parent_taxon_id IS NULL OR parent_taxon_id <> taxon_id),
    CONSTRAINT ck_taxa_scientific_name_not_blank CHECK (length(btrim(scientific_name)) > 0)
);

CREATE TABLE taxon_assignments (
    assignment_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    analysis_id   bigint NOT NULL,
    -- FK to sequencing_libraries added in 090
    library_id    bigint NOT NULL,
    taxon_id      bigint NOT NULL,
    read_count    integer NOT NULL,
    confidence    numeric(5,4) NOT NULL,
    qc_flag       qc_flag NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_taxon_assignments PRIMARY KEY (assignment_id),
    CONSTRAINT fk_taxon_assignments_analysis_id FOREIGN KEY (analysis_id)
        REFERENCES analysis_runs (analysis_id) ON DELETE RESTRICT,
    CONSTRAINT fk_taxon_assignments_taxon_id FOREIGN KEY (taxon_id)
        REFERENCES taxa (taxon_id) ON DELETE RESTRICT,
    CONSTRAINT uq_taxon_assignments_analysis_library_taxon UNIQUE (analysis_id, library_id, taxon_id),
    CONSTRAINT ck_taxon_assignments_read_count CHECK (read_count >= 0),
    CONSTRAINT ck_taxon_assignments_confidence CHECK (confidence BETWEEN 0 AND 1)
);

CREATE TABLE data_exports (
    export_id    bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    -- FK to users added in 090
    requested_by bigint NOT NULL,
    -- FK to projects added in 090
    project_id   bigint NOT NULL,
    export_type  export_type NOT NULL,
    filters      jsonb DEFAULT '{}',
    row_count    integer,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_data_exports PRIMARY KEY (export_id),
    CONSTRAINT ck_data_exports_row_count CHECK (row_count IS NULL OR row_count >= 0)
);
