-- Owner: B (Frontend)
-- Purpose: Tables, keys, CHECK/UNIQUE constraints: Laboratory & Sequencing
--
-- Slice: Laboratory & Sequencing (CONTRACT section 4.3)
-- Tables: laboratories, extraction_batches, dna_extractions, sequencing_runs,
--         sequencing_libraries, quality_control_results
--
-- Rules the schema alone enforces:
--   1. Each re-extraction of a sample gets the next attempt number: UNIQUE (sample_id, attempt_number).
--   2. Concentration and A260/280 purity are never negative.
--   3. A library is built from one extraction and sequenced on one run; the same extraction
--      appears at most once per run: UNIQUE (extraction_id, run_id).
--   4. A QC result belongs to a sample, an analysis run, or both.
--
-- Rules enforced elsewhere (not in this file):
--   - Booking rule: an extraction is in at most one 'planned' or 'running' run at once.
--     Enforced with a row lock by create_sequencing_run() / assign_extraction_to_run()
--     (procedures/lab_procedures.sql, T16).
--   - No library from an extraction that failed QC (triggers/lab_triggers.sql, T17).
--   - sequencing_runs.status transitions (CONTRACT section 3, triggers, T17).
--
-- Columns marked "FK ... added in 090" reference other slices' tables and are plain bigint here,
-- so this file applies on its own after 001. FKs inside this slice use ON DELETE RESTRICT:
-- scientific records are never hard-deleted (D19). Primary keys start at 1000 so seed rows can
-- use explicit IDs below 1000 (D6).

CREATE TABLE laboratories (
    lab_id   bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    name     text NOT NULL,
    location text,
    CONSTRAINT pk_laboratories PRIMARY KEY (lab_id),
    CONSTRAINT uq_laboratories_name UNIQUE (name),
    CONSTRAINT ck_laboratories_name_not_blank CHECK (length(btrim(name)) > 0)
);

CREATE TABLE extraction_batches (
    batch_id        bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    lab_id          bigint NOT NULL,
    -- FK to users added in 090
    operator_id     bigint NOT NULL,
    extraction_date date NOT NULL,
    kit_name        text,
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_extraction_batches PRIMARY KEY (batch_id),
    CONSTRAINT fk_extraction_batches_lab_id FOREIGN KEY (lab_id)
        REFERENCES laboratories (lab_id) ON DELETE RESTRICT
);

CREATE TABLE dna_extractions (
    extraction_id       bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    -- FK to samples added in 090
    sample_id           bigint NOT NULL,
    batch_id            bigint NOT NULL,
    attempt_number      integer NOT NULL DEFAULT 1,
    concentration_ng_ul numeric(10,3),
    purity_a260_280     numeric(5,2),
    qc_status           qc_status NOT NULL DEFAULT 'pending',
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_dna_extractions PRIMARY KEY (extraction_id),
    CONSTRAINT fk_dna_extractions_batch_id FOREIGN KEY (batch_id)
        REFERENCES extraction_batches (batch_id) ON DELETE RESTRICT,
    CONSTRAINT uq_dna_extractions_sample_attempt UNIQUE (sample_id, attempt_number),
    CONSTRAINT ck_dna_extractions_attempt_number CHECK (attempt_number >= 1),
    CONSTRAINT ck_dna_extractions_concentration CHECK (concentration_ng_ul >= 0),
    CONSTRAINT ck_dna_extractions_purity CHECK (purity_a260_280 >= 0)
);

CREATE TABLE sequencing_runs (
    run_id     bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    run_code   text NOT NULL,
    lab_id     bigint NOT NULL,
    platform   text NOT NULL,
    run_date   date,
    status     run_status NOT NULL DEFAULT 'planned',
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_sequencing_runs PRIMARY KEY (run_id),
    CONSTRAINT fk_sequencing_runs_lab_id FOREIGN KEY (lab_id)
        REFERENCES laboratories (lab_id) ON DELETE RESTRICT,
    CONSTRAINT uq_sequencing_runs_run_code UNIQUE (run_code),
    CONSTRAINT ck_sequencing_runs_run_code_not_blank CHECK (length(btrim(run_code)) > 0),
    CONSTRAINT ck_sequencing_runs_platform_not_blank CHECK (length(btrim(platform)) > 0)
);

CREATE TABLE sequencing_libraries (
    library_id    bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    library_code  text NOT NULL,
    extraction_id bigint NOT NULL,
    run_id        bigint NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_sequencing_libraries PRIMARY KEY (library_id),
    CONSTRAINT fk_sequencing_libraries_extraction_id FOREIGN KEY (extraction_id)
        REFERENCES dna_extractions (extraction_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sequencing_libraries_run_id FOREIGN KEY (run_id)
        REFERENCES sequencing_runs (run_id) ON DELETE RESTRICT,
    CONSTRAINT uq_sequencing_libraries_library_code UNIQUE (library_code),
    CONSTRAINT uq_sequencing_libraries_extraction_run UNIQUE (extraction_id, run_id),
    CONSTRAINT ck_sequencing_libraries_library_code_not_blank CHECK (length(btrim(library_code)) > 0)
);

CREATE TABLE quality_control_results (
    qc_id        bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000),
    -- FK to samples added in 090
    sample_id    bigint,
    -- FK to analysis_runs added in 090
    analysis_id  bigint,
    qc_type      qc_type NOT NULL,
    result       qc_result NOT NULL,
    metric_value numeric,
    notes        text,
    -- FK to users added in 090
    recorded_by  bigint,
    recorded_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_quality_control_results PRIMARY KEY (qc_id),
    CONSTRAINT ck_quality_control_results_target CHECK (sample_id IS NOT NULL OR analysis_id IS NOT NULL)
);

