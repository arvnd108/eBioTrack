CREATE TABLE regions (
    region_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name TEXT NOT NULL,
    region_type region_type NOT NULL,
    parent_region_id BIGINT REFERENCES regions(region_id) ON DELETE SET NULL,
    CONSTRAINT uq_regions_name_type UNIQUE (name, region_type)
);

CREATE TABLE sampling_sites (
    site_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    region_id BIGINT NOT NULL REFERENCES regions(region_id),
    name TEXT NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,
    habitat_type habitat_type NOT NULL,
    description TEXT,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_sampling_sites_region_name UNIQUE (region_id, name),
    CONSTRAINT ck_sampling_sites_latitude
        CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_sampling_sites_longitude
        CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE sample_types (
    sample_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    type_name TEXT NOT NULL UNIQUE
);

CREATE TABLE collection_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    project_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL REFERENCES sampling_sites(site_id),
    collector_id BIGINT NOT NULL,
    collected_at TIMESTAMPTZ NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_collection_events_collected_at
        CHECK (collected_at <= now() + INTERVAL '1 day')
);

CREATE TABLE samples (
    sample_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES collection_events(event_id),
    sample_type_id BIGINT NOT NULL REFERENCES sample_types(sample_type_id),
    sample_code TEXT NOT NULL UNIQUE,
    volume_ml NUMERIC(10,2),
    depth_m NUMERIC(8,2),
    storage_location TEXT,
    status sample_status NOT NULL DEFAULT 'collected',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_samples_volume CHECK (volume_ml > 0),
    CONSTRAINT ck_samples_depth CHECK (depth_m >= 0)
);

CREATE TABLE environmental_measurements (
    measurement_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES collection_events(event_id),
    parameter TEXT NOT NULL,
    value NUMERIC NOT NULL,
    unit TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_environmental_measurements_event_parameter
        UNIQUE (event_id, parameter)
);

CREATE TABLE sample_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    sample_id BIGINT NOT NULL REFERENCES samples(sample_id),
    old_status sample_status,
    new_status sample_status NOT NULL,
    changed_by BIGINT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    note TEXT
);
